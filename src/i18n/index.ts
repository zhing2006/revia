export const dictionaries: Record<Locale, Messages> = { en, 'zh-Hans': zhHans, 'zh-Hant': zhHant, ja, ko };
export const localeNames: Record<Locale, string> = { en: 'English', 'zh-Hans': '简体中文', 'zh-Hant': '繁體中文', ja: '日本語', ko: '한국어' };
export function systemLocale(tags: readonly string[]): Locale {
  for (const tag of tags) {
    const lower = tag.toLowerCase();
    if (lower.startsWith('zh')) return /hant|tw|hk|mo/.test(lower) ? 'zh-Hant' : 'zh-Hans';
    if (/^en(?:-|$)/.test(lower)) return 'en';
    if (/^ja(?:-|$)/.test(lower)) return 'ja';
    if (/^ko(?:-|$)/.test(lower)) return 'ko';
  }
  return 'en';
}
export const translate = (locale: Locale, key: string): string => dictionaries[locale][key as MessageKey] ?? en[key as MessageKey] ?? key;
